/**
 * Universal translation helper that looks up translated text for a language code,
 * with fallbacks to English and default text.
 */
export function getTranslation(langCode: string, key: string, fallbackText?: string): string {
  // Normalize code
  const code = langCode.toLowerCase();
  
  if (TRANSLATIONS[code]?.[key]) {
    return TRANSLATIONS[code][key];
  }
  
  // Try base code (e.g. 'en' for 'en-us')
  const baseCode = code.split('-')[0];
  if (TRANSLATIONS[baseCode]?.[key]) {
    return TRANSLATIONS[baseCode][key];
  }

  // Fallback to English
  if (TRANSLATIONS['en']?.[key]) {
    return TRANSLATIONS['en'][key];
  }

  return fallbackText || key;
}
